#!/usr/bin/env node
/**
 * Regenerates docs/udm-1.0.schema.json from the single source of truth: the zod schema in
 * packages/shared/src/udm/schema.ts.
 *
 * Run after changing the UDM: `npm run schema:udm`. `npm run test:api` fails if the committed
 * file is stale, so the published JSON Schema can never drift from what the code validates.
 */

import { writeFileSync, readFileSync, existsSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { pathToFileURL } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(here, '..');
const target = join(repoRoot, 'docs/udm-1.0.schema.json');
const checkOnly = process.argv.includes('--check');

// tsx is used to load the TypeScript source directly; it is a dev dependency.
const { tsImport } = await import('tsx/esm/api');
const { UdmSchema } = await tsImport(
  pathToFileURL(join(repoRoot, 'packages/shared/src/udm/schema.ts')).href,
  import.meta.url,
);
const { zodToJsonSchema } = await tsImport('zod-to-json-schema', import.meta.url);

const generated = zodToJsonSchema(UdmSchema, {
  name: 'Udm',
  $refStrategy: 'root',
  target: 'jsonSchema2019-09',
});

// Metadata first, generated structure last: the generator owns `$ref`/`definitions`, this file
// owns the identity of the document.
const document = {
  $schema: 'https://json-schema.org/draft/2019-09/schema#',
  $id: 'https://idcp.example/schemas/udm-1.0.json',
  title: 'IDCP Universal Data Model 1.0',
  description:
    'Mirrors packages/shared/src/udm/schema.ts. Generated by scripts/generate-udm-schema.mjs — do not edit by hand.',
  ...generated,
};

const serialised = `${JSON.stringify(document, null, 2)}\n`;

if (checkOnly) {
  // Compare structure, not bytes: formatting is the formatter's business, drift is ours.
  let current = null;
  try {
    current = JSON.parse(readFileSync(target, 'utf8'));
  } catch {
    current = null;
  }
  if (!existsSync(target) || JSON.stringify(current) !== JSON.stringify(JSON.parse(serialised))) {
    console.error('docs/udm-1.0.schema.json is out of date. Run: npm run schema:udm');
    process.exit(1);
  }
  console.log('UDM JSON Schema is up to date.');
} else {
  writeFileSync(target, serialised);
  console.log(`Wrote ${target}`);
}
