/**
 * Internationalisation. No user-facing string is hardcoded in a component (AI.md §5).
 * English ships now; adding a locale means adding a catalogue here — no component changes.
 */

export type Locale = 'en' | 'sw' | 'fr';

export const SUPPORTED_LOCALES: Locale[] = ['en', 'sw', 'fr'];

/**
 * Text direction for a language tag.
 *
 * The shipped catalogues are all left-to-right, but the layout is written so that adding an RTL
 * language is a catalogue, not a rewrite: this helper decides the direction and the renderers apply
 * it to the root element and use logical CSS properties throughout (DEC-028).
 */
export type Direction = 'ltr' | 'rtl';

const RTL_LANGUAGES = new Set([
  'ar',
  'arc',
  'ckb',
  'dv',
  'fa',
  'he',
  'iw',
  'ks',
  'ps',
  'sd',
  'ug',
  'ur',
  'yi',
]);

export function directionFor(locale: string | null | undefined): Direction {
  const primary = (locale ?? '').toLowerCase().split(/[-_]/)[0] ?? '';
  return RTL_LANGUAGES.has(primary) ? 'rtl' : 'ltr';
}

export function isRtl(locale: string | null | undefined): boolean {
  return directionFor(locale) === 'rtl';
}

